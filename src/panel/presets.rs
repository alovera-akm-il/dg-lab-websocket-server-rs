//! Pulse waveform presets for the control panel's picker.
//!
//! These are the official waveform patterns bundled with
//! [`dglab-kit`](https://github.com/dungeonlab-open/dglab-kit) (its
//! `COYOTE_WAVEFORMS`/`OVC_WAVEFORMS` tables), transcribed by an
//! automated script that cross-verified every frame byte-for-byte
//! against the upstream TypeScript source before this file was written
//! -- not hand-typed. `Family::Coyote` targets Coyote 3.0 devices, the
//! only device type V3 supports; `Family::Ovc` targets Opossum (OVC)
//! devices, bundled for completeness but not necessarily meaningful on
//! Coyote hardware. If your device isn't a Coyote 3.0, or you want a
//! pattern that isn't in this list, use the panel's custom-waveform
//! field instead.
//!
//! Each frame is 8 bytes (16 hex chars) covering 100ms: 4 bytes of
//! per-25ms-slice data followed by 4 bytes of per-25ms-slice intensity
//! (0x00-0x64, i.e. 0-100). There's no publicly documented byte->Hz
//! formula for the first 4 bytes, which is why these presets are used
//! as opaque, pre-built sequences rather than synthesized from
//! frequency/intensity parameters.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Family {
    Coyote,
    Ovc,
}

impl Family {
    pub fn as_str(self) -> &'static str {
        match self {
            Family::Coyote => "coyote",
            Family::Ovc => "ovc",
        }
    }
}

pub struct Preset {
    pub id: &'static str,
    pub label_en: &'static str,
    pub family: Family,
    pub raw: &'static [&'static str],
}

impl Preset {
    /// Builds the `<prefix>:[...]` wire string V3's `clientMsg` expects
    /// (see [`crate::v3::pulse::parse_pulse_message`]). The prefix
    /// itself is discarded server-side in favor of the request's
    /// resolved channel, so any placeholder text works.
    pub fn waveform_string(&self) -> String {
        format!(
            "X:{}",
            serde_json::to_string(self.raw).expect("&[&str] always serializes")
        )
    }
}

pub fn find(id: &str) -> Option<&'static Preset> {
    PRESETS.iter().find(|p| p.id == id)
}

