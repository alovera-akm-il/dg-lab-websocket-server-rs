#[cfg(test)]
mod tests {
    use super::*;
    use crate::v3::pulse::parse_pulse_message;

    #[test]
    fn preset_count_matches_upstream_dglab_kit() {
        // 24 Coyote + 20 OVC waveforms, per dglab-kit's COYOTE_WAVEFORM /
        // OVC_WAVEFORM enums at the commit this was transcribed from.
        assert_eq!(
            PRESETS
                .iter()
                .filter(|p| p.family == Family::Coyote)
                .count(),
            24
        );
        assert_eq!(
            PRESETS.iter().filter(|p| p.family == Family::Ovc).count(),
            20
        );
        assert_eq!(PRESETS.len(), 44);
    }

    #[test]
    fn all_ids_are_unique() {
        let mut ids: Vec<&str> = PRESETS.iter().map(|p| p.id).collect();
        let before = ids.len();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), before, "duplicate preset id");
    }

    #[test]
    fn all_presets_have_at_least_one_frame_of_exactly_16_hex_chars() {
        for preset in PRESETS {
            assert!(
                !preset.raw.is_empty(),
                "preset {:?} has no frames",
                preset.id
            );
            for frame in preset.raw {
                assert_eq!(
                    frame.len(),
                    16,
                    "preset {:?} has a malformed frame: {frame:?}",
                    preset.id
                );
                assert!(
                    frame.bytes().all(|b| b.is_ascii_hexdigit()),
                    "preset {:?} has a non-hex frame: {frame:?}",
                    preset.id
                );
            }
        }
    }

    #[test]
    fn all_presets_round_trip_through_v3_pulse_parsing() {
        // Confirms the wire string this module builds is exactly what
        // v3::pulse::parse_pulse_message accepts, and that parsing it
        // back out yields the same (uppercased) frames we started with.
        for preset in PRESETS {
            let wire = preset.waveform_string();
            let parsed = parse_pulse_message(&wire)
                .unwrap_or_else(|| panic!("preset {:?} failed to parse: {wire}", preset.id));
            let expected: Vec<String> = preset.raw.iter().map(|f| f.to_ascii_uppercase()).collect();
            assert_eq!(
                parsed, expected,
                "preset {:?} round-trip mismatch",
                preset.id
            );
        }
    }

    #[test]
    fn find_looks_up_by_id() {
        assert!(find("coyote-bubble").is_some());
        assert!(find("ovc-alarm").is_some());
        assert!(find("nonexistent").is_none());
    }
}
